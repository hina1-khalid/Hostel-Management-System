  ok("mess + laundry + gate stats present", rep.stats.mess.mealsBooked >= 1 && rep.stats.laundry.slots > 0 && rep.stats.gate.entries >= 2, JSON.stringify([rep.stats.mess.mealsBooked, rep.stats.laundry.slots, rep.stats.gate.entries]));
