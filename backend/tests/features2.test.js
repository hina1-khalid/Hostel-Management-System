const call = async (method, path, token, body, form) => {
  const headers = token ? { authorization: `Bearer ${token}` } : {};
  if (body && !form) headers["content-type"] = "application/json";
  const r = await fetch(BASE + path, { method, headers, body: form || (body ? JSON.stringify(body) : undefined) });
  const buf = Buffer.from(await r.arrayBuffer());
  let data = null; try { data = JSON.parse(buf.toString()); } catch { /* not json */ }
  return { status: r.status, data, buf, type: r.headers.get("content-type") || "", total: Number(r.headers.get("x-total-count")) };
};
